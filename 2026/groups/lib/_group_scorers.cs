# Arg 2: event
Define("DefaultScorers",
       Concat([ByMatchingValue(FirstNameCluster(Arg<Person>()), -5),
               # Prefer groups 2^k+1. This makes sure that smaller AssignmentSets are effectively spread out, rather  than e.g. putting all of the stage leads back-to-back.
               ByFilters(true, (Mod(GroupNumber(), 2) == 1), 1),
               ByFilters(true, (Mod(GroupNumber(), 4) == 1), 1),
               ByFilters(true, (Mod(GroupNumber(), 8) == 1), 1),
               # But, we don't want stage leads to end up in these groups for other assignment sets, so even
               # more strongly promote these groups for non-stage-leads.
               ByFilters(Not(IsStageLead(Arg<Person>())), (Mod(GroupNumber(), 2) == 1), 1),
               ByFilters(Not(IsStageLead(Arg<Person>())), (Mod(GroupNumber(), 4) == 1), 1),
               ByFilters(Not(IsStageLead(Arg<Person>())), (Mod(GroupNumber(), 8) == 1), 1),
               ByFilters(Not(IsStageLead(Arg<Person>())), (Mod(GroupNumber(), 2) == 1), 1),

               ByFilters((PsychSheetPosition({2, Event}) <= 6),
                         Not(In(Stage(), FinalsStages())),
                         -10)],
              Map(Stages(),
                  ByFilters((AssignedStage(Arg<Person>(), {1, Date}) == Arg<String>()),
                            (Stage() == Arg<String>()), 10))))
